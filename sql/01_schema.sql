-- ============================================================
-- Campus Lost & Found Management System — Database Schema
-- DBMS mini project : MySQL 8.x
--
-- Run order: 01_schema.sql -> 02_programmability.sql -> 04_seed.sql -> 03_queries.sql
-- (02, 03 and 04 rely on tables created by 01)
--
-- NOTE: this script RESETS the database (drops it if it exists) so that
-- 'npm run setup' always produces a clean, reproducible demo state.
-- ============================================================

DROP DATABASE IF EXISTS campus_lost_found;

CREATE DATABASE campus_lost_found
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE campus_lost_found;

-- ------------------------------------------------------------
-- USERS : students and admins
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  user_id     INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  name        VARCHAR(100)     NOT NULL,
  email       VARCHAR(120)     NOT NULL,
  phone       VARCHAR(15)      NOT NULL,
  role        ENUM('STUDENT','ADMIN') NOT NULL DEFAULT 'STUDENT',
  password_hash VARCHAR(255)   NULL,              -- used by ADMIN login only
  created_at  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_users PRIMARY KEY (user_id),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT ck_users_role CHECK (role IN ('STUDENT','ADMIN'))
) ENGINE = InnoDB;

-- ------------------------------------------------------------
-- ITEMS : common item information (shared by lost & found reports)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS items (
  item_id     INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  item_name   VARCHAR(150)     NOT NULL,
  category    VARCHAR(50)      NOT NULL,
  description TEXT             NOT NULL,
  color       VARCHAR(30)      NULL,
  brand       VARCHAR(50)      NULL,
  photo       VARCHAR(255)     NULL,            -- path/URL of uploaded photo
  CONSTRAINT pk_items PRIMARY KEY (item_id),
  CONSTRAINT ck_items_category CHECK (CHAR_LENGTH(TRIM(category)) > 0)
) ENGINE = InnoDB;

-- ------------------------------------------------------------
-- LOCATIONS : campus places (Library, Canteen, ...)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS locations (
  location_id   INT UNSIGNED   NOT NULL AUTO_INCREMENT,
  location_name VARCHAR(80)    NOT NULL,
  CONSTRAINT pk_locations PRIMARY KEY (location_id),
  CONSTRAINT uq_locations_name UNIQUE (location_name)
) ENGINE = InnoDB;

-- ------------------------------------------------------------
-- LOST_REPORTS : "I lost something"
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS lost_reports (
  lost_id     INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  user_id     INT UNSIGNED     NOT NULL,
  item_id     INT UNSIGNED     NOT NULL,
  location_id INT UNSIGNED     NOT NULL,
  lost_date   DATE             NOT NULL,
  lost_time   TIME             NULL,            -- approximate time
  status      ENUM('OPEN','RESOLVED') NOT NULL DEFAULT 'OPEN',
  created_at  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_lost PRIMARY KEY (lost_id),
  CONSTRAINT fk_lost_user    FOREIGN KEY (user_id)     REFERENCES users (user_id),
  CONSTRAINT fk_lost_item    FOREIGN KEY (item_id)     REFERENCES items (item_id),
  CONSTRAINT fk_lost_loc     FOREIGN KEY (location_id) REFERENCES locations (location_id),
  CONSTRAINT ck_lost_status  CHECK (status IN ('OPEN','RESOLVED'))
) ENGINE = InnoDB;

-- ------------------------------------------------------------
-- FOUND_REPORTS : "I found something" (or admin entry from the box)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS found_reports (
  found_id    INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  user_id     INT UNSIGNED     NOT NULL,
  item_id     INT UNSIGNED     NOT NULL,
  location_id INT UNSIGNED     NOT NULL,
  found_date  DATE             NOT NULL,
  found_time  TIME             NULL,
  source      ENUM('USER','BOX') NOT NULL DEFAULT 'USER',
  status      ENUM('UNCLAIMED','RESOLVED') NOT NULL DEFAULT 'UNCLAIMED',
  created_at  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_found PRIMARY KEY (found_id),
  CONSTRAINT fk_found_user FOREIGN KEY (user_id)     REFERENCES users (user_id),
  CONSTRAINT fk_found_item FOREIGN KEY (item_id)     REFERENCES items (item_id),
  CONSTRAINT fk_found_loc  FOREIGN KEY (location_id) REFERENCES locations (location_id),
  CONSTRAINT ck_found_source  CHECK (source IN ('USER','BOX')),
  CONSTRAINT ck_found_status  CHECK (status IN ('UNCLAIMED','RESOLVED'))
) ENGINE = InnoDB;

-- ------------------------------------------------------------
-- MATCHES : possible lost/found pairs generated by the system
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS matches (
  match_id    INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  lost_id     INT UNSIGNED     NOT NULL,
  found_id    INT UNSIGNED     NOT NULL,
  match_score DECIMAL(5,2)     NOT NULL,        -- 0 .. 100
  status      ENUM('PENDING','REJECTED','RESOLVED') NOT NULL DEFAULT 'PENDING',
  created_at  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at TIMESTAMP        NULL,
  CONSTRAINT pk_matches PRIMARY KEY (match_id),
  CONSTRAINT uq_matches_pair UNIQUE (lost_id, found_id),
  CONSTRAINT fk_matches_lost  FOREIGN KEY (lost_id)  REFERENCES lost_reports  (lost_id)  ON DELETE CASCADE,
  CONSTRAINT fk_matches_found FOREIGN KEY (found_id) REFERENCES found_reports (found_id) ON DELETE CASCADE,
  CONSTRAINT ck_matches_score  CHECK (match_score BETWEEN 0 AND 100),
  CONSTRAINT ck_matches_status CHECK (status IN ('PENDING','REJECTED','RESOLVED'))
) ENGINE = InnoDB;

CREATE INDEX idx_lost_status_date  ON lost_reports  (status, lost_date);
CREATE INDEX idx_found_status_date ON found_reports (status, found_date);
CREATE INDEX idx_matches_status    ON matches       (status, match_score DESC);

-- ------------------------------------------------------------
-- APP_SETTINGS : simple key/value configuration (e.g. match threshold)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app_settings (
  env_key    VARCHAR(50)  NOT NULL,
  env_value  VARCHAR(255) NOT NULL,
  CONSTRAINT pk_app_settings PRIMARY KEY (env_key)
) ENGINE = InnoDB;

INSERT INTO app_settings (env_key, env_value)
VALUES ('MATCH_THRESHOLD', '50')
ON DUPLICATE KEY UPDATE env_value = VALUES(env_value);

-- ------------------------------------------------------------
-- VIEWS
-- ------------------------------------------------------------

-- Full detail of every possible match (used by the admin UI).
CREATE OR REPLACE VIEW possible_matches_view AS
SELECT
  m.match_id,
  m.match_score,
  m.status              AS match_status,
  m.created_at          AS match_created_at,
  l.lost_id,
  li.item_name          AS lost_item,
  li.category           AS lost_category,
  li.color              AS lost_color,
  li.brand              AS lost_brand,
  li.photo              AS lost_photo,
  li.description        AS lost_desc,
  lu.name               AS lost_user,
  lu.email              AS lost_email,
  lu.phone              AS lost_phone,
  ll.location_name      AS lost_location,
  l.lost_date,
  l.lost_time,
  l.status              AS lost_status,
  f.found_id,
  fi.item_name          AS found_item,
  fi.category           AS found_category,
  fi.color              AS found_color,
  fi.brand              AS found_brand,
  fi.photo              AS found_photo,
  fi.description        AS found_desc,
  fu.name               AS found_user,
  fu.email              AS found_email,
  fu.phone              AS found_phone,
  fl.location_name      AS found_location,
  f.found_date,
  f.found_time,
  f.source              AS found_source,
  f.status              AS found_status
FROM matches m
JOIN lost_reports  l  ON l.lost_id  = m.lost_id
JOIN found_reports f  ON f.found_id = m.found_id
JOIN items         li ON li.item_id = l.item_id
JOIN items         fi ON fi.item_id = f.item_id
JOIN users         lu ON lu.user_id = l.user_id
JOIN users         fu ON fu.user_id = f.user_id
JOIN locations     ll ON ll.location_id = l.location_id
JOIN locations     fl ON fl.location_id = f.location_id;

-- One row per resolved match: the returned item (for the Resolved page).
CREATE OR REPLACE VIEW resolved_items_view AS
SELECT
  m.match_id,
  m.match_score,
  m.resolved_at,
  li.item_name AS lost_item,
  fi.item_name AS found_item,
  lu.name      AS owner_name,
  lu.email     AS owner_email,
  fu.name      AS finder_name,
  fu.email     AS finder_email,
  ll.location_name AS lost_location,
  fl.location_name AS found_location,
  l.lost_date,
  f.found_date
FROM matches m
JOIN lost_reports  l  ON l.lost_id  = m.lost_id
JOIN found_reports f  ON f.found_id = m.found_id
JOIN items         li ON li.item_id = l.item_id
JOIN items         fi ON fi.item_id = f.item_id
JOIN users         lu ON lu.user_id = l.user_id
JOIN users         fu ON fu.user_id = f.user_id
JOIN locations     ll ON ll.location_id = l.location_id
JOIN locations     fl ON fl.location_id = f.location_id
WHERE m.status = 'RESOLVED';
